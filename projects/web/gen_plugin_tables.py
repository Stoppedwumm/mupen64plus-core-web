#!/usr/bin/env python3
"""Generate the static symbol tables for plugins linked into the web build.

Usage: gen_plugin_tables.py <api dir> <output.c> <name:prefix:rename.h>...

Every plugin's globals are renamed with a prefix (see build.sh). For each
plugin this emits a NULL-terminated osal_static_symbol table named
web_plugin_<name> mapping the plugin API entry point names (as looked up by
the core) to the renamed functions. The table pointer is what the frontend
passes to CoreAttachPlugin()/PluginStartup() as the library handle.
"""

import os
import re
import sys


def api_function_names(api_dir):
    """Plugin API entry points, i.e. ptr_* typedefs from m64p_plugin.h."""
    with open(os.path.join(api_dir, "m64p_plugin.h")) as f:
        names = re.findall(r"typedef\s+[^;]*?\(\s*\*\s*ptr_(\w+)\s*\)", f.read())
    return set(names) | {"PluginStartup", "PluginShutdown", "PluginGetVersion"}


def main():
    api_dir, output = sys.argv[1], sys.argv[2]
    api = api_function_names(api_dir)

    out = [
        "/* generated by projects/web/gen_plugin_tables.py - do not edit */",
        "#include <stddef.h>",
        '#include "m64p_common.h"',
        '#include "m64p_plugin.h"',
        '#include "osal/dynamiclib.h"',
        "",
    ]
    for spec in sys.argv[3:]:
        name, prefix, rename = spec.split(":", 2)
        with open(rename) as f:
            defined = set(re.findall(r"^#define (\w+) ", f.read(), re.M))
        exported = sorted(api & defined)

        out.append("/* %s */" % name)
        for sym in exported:
            out.append("extern __typeof__(*(ptr_%s) 0) %s%s;" % (sym, prefix, sym))
        out.append("const osal_static_symbol web_plugin_%s[] = {" % name.replace("-", "_"))
        for sym in exported:
            out.append('    { "%s", (m64p_function) %s%s },' % (sym, prefix, sym))
        out.append("    { NULL, NULL }")
        out.append("};")
        out.append("")

    with open(output, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
